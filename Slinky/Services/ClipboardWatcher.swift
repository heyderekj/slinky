import AppKit
import SlinkyCoreShared
import SwiftUI

/// Save from clipboard (off unless turned on in Settings): when you copy something shaped like a key in another app,
/// Slinky offers to save it. It checks the shape only, keeps nothing unless you choose Save, skips anything a password
/// manager marks concealed or transient, and skips Slinky's own copies. Nothing is sent anywhere.
@MainActor
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var banner: NSPanel?

    private static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardWatcher.shared.tick() }
        }
    }

    private func tick() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard Preferences.shared.offerToSaveCopies, let item = board.pasteboardItems?.first else { return }
        let types = Set(item.types.map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes), item.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source")) != "com.slinky.app",
              let text = item.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              (12...4096).contains(text.count), !text.contains("\n"),
              let detection = Detector.detect(text), detection.kind == .apiKey || detection.kind == .recoveryKey else { return }
        let model = AppModel.shared
        if model.isUnlocked, !model.places(of: text).isEmpty { return }   // Already saved.
        show(label: detection.label, value: text)
    }

    private func show(label: String, value: String) {
        banner?.close()
        let panel = NSPanel(contentRect: NSRect(x: 0, y: 0, width: 360, height: 76), styleMask: [.nonactivatingPanel, .borderless],
                            backing: .buffered, defer: false)
        panel.isFloatingPanel = true
        panel.level = .statusBar
        panel.backgroundColor = .clear
        panel.isOpaque = false
        panel.hasShadow = true
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        panel.contentView = NSHostingView(rootView: SaveBanner(label: label, save: { [weak self] in
            self?.dismiss()
            self?.save(value)
        }, dismiss: { [weak self] in self?.dismiss() }).symbolVariant(.fill))
        if let screen = NSScreen.main {
            let f = screen.visibleFrame
            panel.setFrameOrigin(NSPoint(x: f.maxX - 376, y: f.maxY - 92))
        }
        panel.orderFrontRegardless()
        banner = panel
        let shown = panel
        Task { @MainActor in
            try? await Task.sleep(for: .seconds(10))
            if self.banner === shown { self.dismiss() }
        }
    }

    private func dismiss() {
        banner?.close()
        banner = nil
    }

    private func save(_ value: String) {
        let model = AppModel.shared
        model.openMainWindow?()
        if model.isUnlocked {
            model.openAddItem(prefill: value)
        } else {
            model.pendingSave = value
            model.unlock()
        }
    }
}

private struct SaveBanner: View {
    let label: String
    let save: () -> Void
    let dismiss: () -> Void

    var body: some View {
        HStack(spacing: 12) {
            KeyholeMark(size: 34)
            VStack(alignment: .leading, spacing: 2) {
                Text(label).font(.callout.weight(.semibold)).lineLimit(1)
                Text("Save it to Slinky?").font(.caption).foregroundStyle(.secondary)
            }
            Spacer(minLength: 6)
            Button("Not Now", action: dismiss).controlSize(.small)
            Button("Save", action: save).glassProminentButton().controlSize(.small)
        }
        .padding(.horizontal, 14)
        .frame(width: 360, height: 76)
        .glass(in: .rect(cornerRadius: 18))
    }
}
